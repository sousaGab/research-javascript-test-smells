const VALUE_WITHIN_RANGE = 5;
const VALUE_BELOW_RANGE = 0;
const VALUE_ABOVE_RANGE = 15;
const STRING_NUMERIC_VALUE = "7";
const STRING_NON_NUMERIC_VALUE = "abc";
const NAN_VALUE = NaN;

const MIN_BOUNDARY = 1;
const MAX_BOUNDARY = 10;
const SECOND_MIN_BOUNDARY = 2;
const SECOND_MAX_BOUNDARY = 5;

const EXPECTED_WITHIN_RANGE = 5;
const EXPECTED_CLAMPED_TO_MIN = 1;
const EXPECTED_CLAMPED_TO_MAX = 10;
const EXPECTED_COERCED_NUMERIC = 7;
const EXPECTED_FALLBACK_TO_MIN = 1;
const EXPECTED_NAN_FALLBACK = 2;

it("should test clampValue", () => {
    expect(clampValue(VALUE_WITHIN_RANGE, MIN_BOUNDARY, MAX_BOUNDARY)).toBe(EXPECTED_WITHIN_RANGE);
    expect(clampValue(VALUE_BELOW_RANGE, MIN_BOUNDARY, MAX_BOUNDARY)).toBe(EXPECTED_CLAMPED_TO_MIN);
    expect(clampValue(VALUE_ABOVE_RANGE, MIN_BOUNDARY, MAX_BOUNDARY)).toBe(EXPECTED_CLAMPED_TO_MAX);

    // string inputs are coerced numerically by Math.min/Math.max
    // @ts-ignore
    expect(clampValue(STRING_NUMERIC_VALUE, MIN_BOUNDARY, MAX_BOUNDARY)).toBe(EXPECTED_COERCED_NUMERIC);

    // non-numeric and NaN fall back to min
    // @ts-ignore
    expect(clampValue(STRING_NON_NUMERIC_VALUE, MIN_BOUNDARY, MAX_BOUNDARY)).toBe(EXPECTED_FALLBACK_TO_MIN);
    expect(clampValue(NAN_VALUE, SECOND_MIN_BOUNDARY, SECOND_MAX_BOUNDARY)).toBe(EXPECTED_NAN_FALLBACK);
});